/**
 * Extension generator — produces the complete directory structure for a generated extension.
 *
 * For each service, generates:
 * - manifest.yaml
 * - deno.json
 * - README.md
 * - LICENSE.md (copied from template)
 * - RELEASE_NOTES.md
 * - .swamp.yaml
 * - .gitignore
 * - extensions/models/cloudflare/{name}.ts
 * - extensions/models/cloudflare/{name}_test.ts
 * - extensions/models/cloudflare/_lib/api.ts (shared helper)
 */

import type { ServiceConfig } from "../config.ts";
import { OUTPUT_BASE, SWAMP_TESTING_VERSION } from "../config.ts";

/** Generate manifest.yaml content */
export function generateManifest(
  config: ServiceConfig,
  version: string,
  modelFileName: string,
): string {
  return `manifestVersion: 1
name: "@webframp/cloudflare/${config.name}"
version: "${version}"
description: "${config.description}"
repository: "https://github.com/webframp/swamp-extensions"
models:
  - cloudflare/${modelFileName}
platforms:
  - linux-x86_64
  - linux-aarch64
  - darwin-x86_64
  - darwin-aarch64
additionalFiles:
  - README.md
  - LICENSE.md
labels:
${config.labels.map((l) => `  - ${l}`).join("\n")}
`;
}

/** Generate deno.json content */
export function generateDenoJson(): string {
  return JSON.stringify(
    {
      compilerOptions: { strict: true },
      tasks: {
        check:
          "deno check extensions/models/cloudflare/*.ts extensions/models/cloudflare/_lib/*.ts",
        lint: "deno lint extensions/models/",
        fmt: "deno fmt extensions/models/",
        "fmt:check": "deno fmt --check extensions/models/",
        test: "deno test --allow-env --allow-net extensions/models/",
      },
      lint: {
        rules: {
          exclude: ["no-import-prefix"],
        },
      },
      imports: {
        "@systeminit/swamp-testing":
          `jsr:@systeminit/swamp-testing@${SWAMP_TESTING_VERSION}`,
      },
    },
    null,
    2,
  ) + "\n";
}

/** Generate README.md for the extension */
export function generateReadme(
  config: ServiceConfig,
  methods: { name: string; description: string; type: string }[],
): string {
  const scopeArg = config.scope === "account"
    ? "accountId=YOUR_ACCOUNT_ID"
    : "zoneId=YOUR_ZONE_ID";

  return `# @webframp/cloudflare/${config.name}

${config.description}

Auto-generated by \`scripts/cloudflare-codegen\` from the Cloudflare OpenAPI specification.

## Usage

\`\`\`bash
swamp extension pull @webframp/cloudflare/${config.name}

swamp model create @webframp/cloudflare/${config.name} cf-${config.name} \\
  --global-arg apiToken=CLOUDFLARE_API_TOKEN \\
  --global-arg ${scopeArg}
\`\`\`

## Methods

| Method | Description |
|--------|-------------|
${methods.map((m) => `| \`${m.name}\` | ${m.description} |`).join("\n")}

## Development

\`\`\`bash
cd ${OUTPUT_BASE}/${config.name}
deno task check
deno task lint
deno task fmt
deno task test
\`\`\`

## License

Apache-2.0 — see [LICENSE.md](LICENSE.md).
`;
}

/** Generate RELEASE_NOTES.md */
export function generateReleaseNotes(
  config: ServiceConfig,
  version: string,
  methodCount: number,
  body?: string,
): string {
  // A regeneration is not an initial release. Claiming otherwise in every
  // version's notes misleads the consumers the notes exist for, so callers
  // supply the body for anything but a first release.
  const text = body ??
    `**Added:** Initial code-generated release of @webframp/cloudflare/${config.name} with ${methodCount} methods covering the Cloudflare ${
      config.name.replace(/-/g, " ")
    } API surface.`;
  return `## ${version}

${text.trimEnd()}
`;
}

/**
 * Generate .swamp.yaml, preserving an existing repoId.
 *
 * swamp mints `repoId` lazily into the marker on first invocation in a
 * directory; the generator never creates one. Regenerating with a fresh marker
 * therefore DELETES the repoId, which is the identity swamp uses for that repo.
 * Any existing value is carried forward.
 *
 * `existing` is the current file contents, or undefined when the extension is
 * being created for the first time.
 */
export function generateSwampYaml(existing?: string): string {
  let repoIdLine = "";
  if (existing) {
    const match = existing.match(/^repoId:\s*(\S+)\s*$/m);
    if (match) repoIdLine = `repoId: ${match[1]}\n`;
  }
  return `# Swamp repository marker
# Generated by scripts/cloudflare-codegen
repoVersion: 1
${repoIdLine}`;
}

