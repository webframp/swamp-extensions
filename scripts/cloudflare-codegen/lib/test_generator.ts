/**
 * Test generator — produces test files for generated models.
 *
 * Generates tests matching the existing Cloudflare extension test pattern:
 * - Model structure tests (type, version, methods, resources)
 * - Mock HTTP server tests (one per method type)
 *
 * Test fixtures are synthesized from the OpenAPI response schemas.
 */

import {
  type ClassifiedMethod,
  createInstanceSource,
  type MethodSecretPlan,
  planSecrets,
  resourceNameOf,
} from "./method_classifier.ts";
import type { SchemaObject } from "./schema_fetcher.ts";
