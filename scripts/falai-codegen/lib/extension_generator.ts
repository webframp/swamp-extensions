/** Generate RELEASE_NOTES.md */
export function generateReleaseNotes(
  config: ServiceConfig,
  version: string,
  methodCount: number,
  body?: string,
): string {
  const text = body ??
    `**Added:** Initial code-generated release of @webframp/falai/${config.name} with ${methodCount} methods covering the fal.ai ${
      config.name.replace(/-/g, " ")
    } API surface.`;
  return `## ${version}

${text.trimEnd()}
`;
}

/**
 * Generate .swamp.yaml, preserving an existing repoId.
 *
 * swamp mints `repoId` lazily into the marker on first invocation in a
 * directory; the generator never creates one. Regenerating with a fresh
 * marker would DELETE the repoId, so any existing value is carried forward.
 */
export function generateSwampYaml(existing?: string): string {
  let repoIdLine = "";
  if (existing) {
    const match = existing.match(/^repoId:\s*(\S+)\s*$/m);
    if (match) repoIdLine = `repoId: ${match[1]}\n`;
  }
  return `# Swamp repository marker
# Generated by scripts/falai-codegen
repoVersion: 1
${repoIdLine}`;
}

