/**
 * Test generator — produces test files for generated models.
 *
 * Generates tests matching the existing swamp extension test pattern:
 * - Model structure tests (type, version, methods, resources)
 * - Mock HTTP server tests (one per method type)
 *
 * fal.ai responses are bare JSON objects (no {success, result} envelope), so
 * the mock server here returns the fixture directly — for list methods,
 * nested under the operation's detected `resultsField` name.
 *
 * Test fixtures are synthesized from the OpenAPI response schemas.
 */

import type { ClassifiedMethod } from "./method_classifier.ts";
import type { SchemaObject } from "./schema_fetcher.ts";
import type { ServiceConfig } from "../config.ts";

/**
 * The value substituted for every path parameter in generated tests.
 */
export const PATH_PARAM_TEST_VALUE = "test-id-123";

/** Generate a complete test file for a service */
export function generateTestSource(
  config: ServiceConfig,
  methods: ClassifiedMethod[],
  modelFileName: string,
): string {
  const lines: string[] = [];

  lines.push(`// ${config.description} — Tests`);
  lines.push(
    `// Auto-generated by scripts/falai-codegen — do not edit manually.`,
  );
  lines.push(`// SPDX-License-Identifier: Apache-2.0`);
  lines.push(``);
  lines.push(
    `import { assertEquals, assertExists } from "jsr:@std/assert@1.0.19";`,
  );
  lines.push(
    `import { createModelTestContext } from "@systeminit/swamp-testing";`,
  );
  lines.push(`import { model } from "./${modelFileName}.ts";`);
  lines.push(``);

  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(`// Model Export Structure Tests`);
  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(``);

  lines.push(`Deno.test("${config.name} model: has correct type", () => {`);
  lines.push(
    `  assertEquals(model.type, "@webframp/falai/${config.name}");`,
  );
  lines.push(`});`);
  lines.push(``);

  lines.push(
    `Deno.test("${config.name} model: has valid version format", () => {`,
  );
  lines.push(`  const versionPattern = /^\\d{4}\\.\\d{2}\\.\\d{2}\\.\\d+$/;`);
  lines.push(`  assertEquals(versionPattern.test(model.version), true);`);
  lines.push(`});`);
  lines.push(``);

  lines.push(
    `Deno.test("${config.name} model: has globalArguments with apiToken", () => {`,
  );
  lines.push(`  assertExists(model.globalArguments);`);
  lines.push(`  const shape = model.globalArguments.shape;`);
  lines.push(`  assertExists(shape.apiToken);`);
  lines.push(`});`);
  lines.push(``);

  lines.push(
    `Deno.test("${config.name} model: has expected methods", () => {`,
  );
  lines.push(`  assertExists(model.methods);`);
  for (const method of methods) {
    lines.push(`  assertExists(model.methods.${method.name});`);
  }
  lines.push(`});`);
  lines.push(``);

  const resources = methods
    .filter((m) => m.type !== "delete")
    .map((m) => {
      if (m.type === "list") return m.name.replace(/^list_/, "");
      return m.name.replace(/^(get|create|update|action)_/, "");
    });
  const uniqueResources = [...new Set(resources)];

  lines.push(
    `Deno.test("${config.name} model: has expected resources", () => {`,
  );
  lines.push(`  assertExists(model.resources);`);
  for (const r of uniqueResources) {
    lines.push(`  assertExists(model.resources["${r}"]);`);
  }
  lines.push(`});`);
  lines.push(``);

  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(`// Mock fal.ai API Server`);
  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(``);
  lines.push(generateMockServer());
  lines.push(``);

  const testedTypes = new Set<string>();
  for (const method of methods) {
    if (testedTypes.has(method.type)) continue;
    testedTypes.add(method.type);
    lines.push(generateExecutionTest(config, method));
    lines.push(``);
  }

  return lines.join("\n");
}

/** Generate the mock HTTP server helper */
function generateMockServer(): string {
  return `function startMockFalServer(
  responses: Record<string, { body: unknown }>,
): { url: string; server: Deno.HttpServer } {
  const server = Deno.serve({ port: 0, onListen() {} }, (req) => {
    const url = new URL(req.url);
    const path = url.pathname;

    for (const [pattern, { body }] of Object.entries(responses)) {
      if (path.includes(pattern)) {
        return Response.json(body);
      }
    }

    return Response.json(
      { error: { type: "not_found", message: "Not found" } },
      { status: 404 },
    );
  });

  const addr = server.addr as Deno.NetAddr;
  return { url: \`http://localhost:\${addr.port}\`, server };
}

function installFetchMock(mockUrl: string): () => void {
  const originalFetch = globalThis.fetch;
  globalThis.fetch = (input, init) => {
    const reqUrl = typeof input === "string" ? input : input.toString();
    const newUrl = reqUrl.replace("https://api.fal.ai/v1", mockUrl);
    return originalFetch(newUrl, init);
  };
  return () => {
    globalThis.fetch = originalFetch;
  };
}`;
}

/** Generate an execution test for a method */
function generateExecutionTest(
  config: ServiceConfig,
  method: ClassifiedMethod,
): string {
  const globalArgs: Record<string, string> = { apiToken: "test-token" };

  const fixture = generateFixture(method);
  const pathPattern = extractPathPattern(method.operation.path);
  const testArgs = buildTestArgs(method);

  if (method.type === "list") {
    const resultsField = method.operation.pagination.resultsField ??
      resourceNameFor(method);
    const argsStr = Object.keys(testArgs).length > 0
      ? JSON.stringify(testArgs)
      : "{}";
    return `Deno.test({
  name: "${config.name} model: ${method.name} fetches and writes resource",
  sanitizeResources: false,
  fn: async () => {
    const mockBody = { ${JSON.stringify(resultsField)}: [${
      JSON.stringify(fixture)
    }] };
    const { url, server } = startMockFalServer({
      "${pathPattern}": { body: mockBody },
    });
    const uninstall = installFetchMock(url);

    try {
      const { context, getWrittenResources } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        definition: { id: "test-id", name: "test-${config.name}", version: 1, tags: {} },
      });

      const result = await (model.methods as Record<string, { execute: (args: Record<string, unknown>, ctx: unknown) => Promise<{ dataHandles: unknown[] }> }>).${method.name}.execute(${argsStr}, context);
      assertEquals(result.dataHandles.length, 1);

      const resources = getWrittenResources();
      assertEquals(resources.length, 1);
    } finally {
      uninstall();
      await server.shutdown();
    }
  },
});`;
  }

  if (method.type === "get") {
    return `Deno.test({
  name: "${config.name} model: ${method.name} fetches and writes resource",
  sanitizeResources: false,
  fn: async () => {
    const mockBody = ${JSON.stringify(fixture)};
    const { url, server } = startMockFalServer({
      "${pathPattern}": { body: mockBody },
    });
    const uninstall = installFetchMock(url);

    try {
      const { context, getWrittenResources } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        definition: { id: "test-id", name: "test-${config.name}", version: 1, tags: {} },
      });

      const result = await (model.methods as Record<string, { execute: (args: Record<string, unknown>, ctx: unknown) => Promise<{ dataHandles: unknown[] }> }>).${method.name}.execute(${
      JSON.stringify(testArgs)
    }, context);
      assertEquals(result.dataHandles.length, 1);

      const resources = getWrittenResources();
      assertEquals(resources.length, 1);
    } finally {
      uninstall();
      await server.shutdown();
    }
  },
});`;
  }

  if (method.type === "create") {
    const createArgs = buildFinalTestArgs(method, fixture);
    return `Deno.test({
  name: "${config.name} model: ${method.name} creates and writes resource",
  sanitizeResources: false,
  fn: async () => {
    const mockBody = ${JSON.stringify({ id: "new-123", ...fixture })};
    const { url, server } = startMockFalServer({
      "${pathPattern}": { body: mockBody },
    });
    const uninstall = installFetchMock(url);

    try {
      const { context, getWrittenResources } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        definition: { id: "test-id", name: "test-${config.name}", version: 1, tags: {} },
      });

      const result = await (model.methods as Record<string, { execute: (args: Record<string, unknown>, ctx: unknown) => Promise<{ dataHandles: unknown[] }> }>).${method.name}.execute(${
      JSON.stringify(createArgs)
    }, context);
      assertEquals(result.dataHandles.length, 1);

      const resources = getWrittenResources();
      assertEquals(resources.length, 1);
    } finally {
      uninstall();
      await server.shutdown();
    }
  },
});`;
  }

  if (method.type === "delete") {
    return `Deno.test({
  name: "${config.name} model: ${method.name} executes successfully",
  sanitizeResources: false,
  fn: async () => {
    const { url, server } = startMockFalServer({
      "${pathPattern}": { body: { id: "${PATH_PARAM_TEST_VALUE}" } },
    });
    const uninstall = installFetchMock(url);

    try {
      const { context } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        definition: { id: "test-id", name: "test-${config.name}", version: 1, tags: {} },
      });

      const result = await (model.methods as Record<string, { execute: (args: Record<string, unknown>, ctx: unknown) => Promise<{ dataHandles: unknown[] }> }>).${method.name}.execute(${
      JSON.stringify(testArgs)
    }, context);
      assertEquals(result.dataHandles.length, 0);
    } finally {
      uninstall();
      await server.shutdown();
    }
  },
});`;
  }

  // Default: action/update
  const actionArgs = buildFinalTestArgs(method, fixture);
  return `Deno.test({
  name: "${config.name} model: ${method.name} executes and writes resource",
  sanitizeResources: false,
  fn: async () => {
    const mockBody = ${JSON.stringify(fixture)};
    const { url, server } = startMockFalServer({
      "${pathPattern}": { body: mockBody },
    });
    const uninstall = installFetchMock(url);

    try {
      const { context, getWrittenResources } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        definition: { id: "test-id", name: "test-${config.name}", version: 1, tags: {} },
      });

      const result = await (model.methods as Record<string, { execute: (args: Record<string, unknown>, ctx: unknown) => Promise<{ dataHandles: unknown[] }> }>).${method.name}.execute(${
    JSON.stringify(actionArgs)
  }, context);
      assertEquals(result.dataHandles.length, 1);

      const resources = getWrittenResources();
      assertEquals(resources.length, 1);
    } finally {
      uninstall();
      await server.shutdown();
    }
  },
});`;
}

function resourceNameFor(method: ClassifiedMethod): string {
  return method.type === "list"
    ? method.name.replace(/^list_/, "")
    : method.name.replace(/^(get|create|update|action)_/, "");
}

/** Generate a synthetic fixture from a response schema */
function generateFixture(method: ClassifiedMethod): Record<string, unknown> {
  const schema = method.operation.responseSchema;
  if (!schema) return { id: "fixture-123" };
  return synthesizeValue(schema) as Record<string, unknown>;
}

/** Synthesize a value matching a schema (for test fixtures) */
function synthesizeValue(schema: SchemaObject, depth = 0): unknown {
  if (depth > 4) return null;

  if (schema.example !== undefined) return schema.example;

  if (schema.enum) {
    const nonNull = schema.enum.filter((v) => v !== null);
    if (nonNull.length > 0) return nonNull[0];
  }

  if (schema.oneOf || schema.anyOf) {
    return synthesizeValue((schema.oneOf ?? schema.anyOf)![0], depth + 1);
  }

  const type = Array.isArray(schema.type)
    ? schema.type.find((t) => t !== "null")
    : schema.type;

  switch (type) {
    case "string":
      if (schema.format === "date-time") return "2024-01-01T00:00:00Z";
      if (schema.format === "uri" || schema.format === "url") {
        return "https://example.com";
      }
      return "test-value";
    case "number":
    case "integer":
      return schema.minimum ?? 1;
    case "boolean":
      return true;
    case "array":
      if (schema.items) {
        return [synthesizeValue(schema.items, depth + 1)];
      }
      return [];
    case "object":
      if (schema.properties) {
        const obj: Record<string, unknown> = {};
        for (const [name, prop] of Object.entries(schema.properties)) {
          obj[name] = synthesizeValue(prop, depth + 1);
        }
        return obj;
      }
      return {};
    default:
      return null;
  }
}

/**
 * Extract a path pattern for mock server matching.
 *
 * fal.ai paths carry no account/zone scope segment to strip — every path
 * parameter is simply replaced with a fixed test value. The mock server uses
 * path.includes(pattern) for matching.
 */
export function extractPathPattern(path: string): string {
  let result = path.replace(/\{[^}]+\}/g, PATH_PARAM_TEST_VALUE);
  result = result.replace(/\/$/, "");
  return result;
}

/** Build test args that include path param values matching the mock pattern */
function buildTestArgs(method: ClassifiedMethod): Record<string, unknown> {
  const args: Record<string, unknown> = {};
  for (const p of method.operation.pathParams) {
    args[p.name.replace(/-/g, "_")] = PATH_PARAM_TEST_VALUE;
  }
  return args;
}

/**
 * Merge a request-body fixture with the path-param values, path params winning.
 *
 * Exported for direct unit testing.
 */
export function buildFinalTestArgs(
  method: ClassifiedMethod,
  fixture: Record<string, unknown>,
): Record<string, unknown> {
  return { ...fixture, ...buildTestArgs(method) };
}
