/** Generate RELEASE_NOTES.md. */
export function generateReleaseNotes(
  config: ServiceConfig,
  version: string,
  methodCount: number,
  body?: string,
): string {
  const text = body ??
    `**Added:** Initial code-generated release of @webframp/griptape/${config.name} with ${methodCount} methods covering the Griptape Cloud ${
      config.name.replace(/-/g, " ")
    } API surface.`;
  return `## ${version}

${text.trimEnd()}
`;
}

/**
 * Generate .swamp.yaml, preserving an existing repoId. `existing` is the
 * current file contents, or undefined when the extension is new.
 */
export function generateSwampYaml(existing?: string): string {
  let repoIdLine = "";
  if (existing) {
    const match = existing.match(/^repoId:\s*(\S+)\s*$/m);
    if (match) repoIdLine = `repoId: ${match[1]}\n`;
  }
  return `# Swamp repository marker
# Generated by scripts/griptape-codegen
repoVersion: 1
${repoIdLine}`;
}

/** Generate .gitignore. */
export function generateGitignore(): string {
  return `.swamp/
CLAUDE.md
AGENTS.md
`;
}

/**
 * Generate the shared _lib/api.ts helper.
 *
 * Griptape Cloud: Bearer auth, no response envelope (entities are returned
 * flat), page-based pagination (`page`/`page_size` in; a `pagination` object
 * with `total_pages` out). griptapeApiPaginated takes the resource-named array
 * key because list responses have no fixed collection key.
 */
export function generateApiLib(): string {
  return `// Griptape Cloud API Helper
// Shared utilities for all Griptape models
// Auto-generated by scripts/griptape-codegen — do not edit manually.
// SPDX-License-Identifier: Apache-2.0

const DEFAULT_API_BASE = "${GRIPTAPE_API_BASE}";

/**
 * Resolve the Griptape Cloud API base URL: an explicit baseUrl global arg wins,
 * then the GT_CLOUD_BASE_URL environment variable, then the built-in default.
 */
function resolveBaseUrl(baseUrl?: string): string {
  return baseUrl || Deno.env.get("GT_CLOUD_BASE_URL") || DEFAULT_API_BASE;
}

/**
 * Resolve the Griptape Cloud API key: an explicit key (typically from the
 * model's vault-wireable apiKey global arg) takes precedence over the
 * GT_CLOUD_API_KEY environment variable. Throws when neither is set.
 */
function resolveKey(apiKey?: string): string {
  const key = apiKey || Deno.env.get("GT_CLOUD_API_KEY");
  if (!key) {
    throw new Error(
      "Griptape Cloud API key not set. Provide the apiKey global argument " +
        "(wireable with a vault.get(...) expression) or set the " +
        "GT_CLOUD_API_KEY environment variable.",
    );
  }
  return key;
}

/**
 * Sanitize a resource instance name for swamp's data layer.
 *
 * Swamp rejects data-artifact instance names containing "/", "\\\\", "..", or
 * null bytes (path-traversal protection). Instance names are frequently derived
 * from API-returned identifiers, so every writeResource instance name is routed
 * through this before it reaches the datastore.
 */
export function sanitizeInstanceName(name: string): string {
  return name
    .replace(/[/\\\\]/g, "_")
    .replace(/\\.\\./g, "_")
    .replace(/\\0/g, "");
}

const MAX_RETRIES = 3;

/**
 * fetch with bounded retry on HTTP 429. Honors Retry-After (seconds) when
 * present, otherwise backs off linearly. Returns the final Response.
 */
async function gtFetch(url: string, init: RequestInit): Promise<Response> {
  for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
    const response = await fetch(url, init);
    if (response.status !== 429) return response;

    const retryAfter = response.headers.get("Retry-After");
    const parsed = retryAfter ? Number(retryAfter) : NaN;
    const delayMs = Number.isFinite(parsed) ? parsed * 1000 : 1000 * (attempt + 1);
    await response.text();
    if (attempt < MAX_RETRIES) {
      await new Promise((r) => setTimeout(r, delayMs));
      continue;
    }
    return response;
  }
  throw new Error(\`Griptape API request failed: \${url}\`);
}

/** Perform a single JSON request against the Griptape Cloud API. */
export async function griptapeApi<T>(
  apiKey: string,
  method: string,
  path: string,
  body?: unknown,
  baseUrl?: string,
): Promise<T> {
  const key = resolveKey(apiKey);
  const url = \`\${resolveBaseUrl(baseUrl)}\${path}\`;
  const headers: Record<string, string> = {
    "Authorization": \`Bearer \${key}\`,
    "Content-Type": "application/json",
  };

  const response = await gtFetch(url, {
    method,
    headers,
    body: body ? JSON.stringify(body) : undefined,
  });

  if (response.status === 429) {
    await response.text();
    throw new Error(\`Griptape API rate limited after \${MAX_RETRIES} retries: \${method} \${path}\`);
  }

  if (!response.ok) {
    const text = await response.text();
    throw new Error(\`Griptape API error: \${method} \${path} returned \${response.status} \${response.statusText}: \${text.slice(0, 500)}\`);
  }

  // 204 No Content (deletes) — nothing to parse.
  if (response.status === 204) return undefined as unknown as T;

  const text = await response.text();
  if (!text) return undefined as unknown as T;
  return JSON.parse(text) as T;
}

const MAX_PAGES = ${MAX_PAGES};

export interface PaginatedResult<T> {
  results: T[];
  truncated: boolean;
  totalFetched: number;
}

interface Pagination {
  page_number?: number;
  page_size?: number;
  total_count?: number;
  total_pages?: number;
  next_page?: number;
}

/**
 * Page-based pagination over a Griptape list endpoint.
 *
 * Griptape list responses have no fixed collection key: each wrapper carries a
 * resource-named array (\`threads\`, \`structures\`, ...) plus a \`pagination\`
 * object. \`itemsKey\` names the array to read. Stops when the reported page
 * reaches total_pages, when a page returns nothing, or at MAX_PAGES (in which
 * case truncated=true).
 */
export async function griptapeApiPaginated<T>(
  apiKey: string,
  path: string,
  itemsKey: string,
  params?: Record<string, string>,
  baseUrl?: string,
): Promise<PaginatedResult<T>> {
  const key = resolveKey(apiKey);
  const base = resolveBaseUrl(baseUrl);
  const allResults: T[] = [];
  const pageSize = 50;
  let page = 1;
  let truncated = false;

  while (page <= MAX_PAGES) {
    const queryParams = new URLSearchParams({
      ...params,
      page: String(page),
      page_size: String(pageSize),
    });
    const url = \`\${base}\${path}?\${queryParams}\`;

    const response = await gtFetch(url, {
      headers: { "Authorization": \`Bearer \${key}\` },
    });

    if (response.status === 429) {
      await response.text();
      throw new Error(\`Griptape API rate limited after \${MAX_RETRIES} retries: GET \${path}\`);
    }
    if (!response.ok) {
      const text = await response.text();
      throw new Error(\`Griptape API error: GET \${path} returned \${response.status} \${response.statusText}: \${text.slice(0, 500)}\`);
    }

    const data = (await response.json()) as Record<string, unknown>;
    const rawItems = data[itemsKey];
    if (!Array.isArray(rawItems)) {
      // The itemsKey named at codegen time is not an array in this response.
      // If the response carries a DIFFERENT array property, itemsKey is wrong
      // and silently returning [] would be a false empty-success — fail loudly.
      // If there is no array at all (e.g. an empty/error-shaped body), treat it
      // as an empty page and stop.
      const otherArrayKey = Object.keys(data).find(
        (k) => k !== itemsKey && k !== "pagination" && Array.isArray(data[k]),
      );
      if (otherArrayKey) {
        throw new Error(
          \`Griptape API: GET \${path} response has no array at "\${itemsKey}" \` +
            \`but does at "\${otherArrayKey}". The generated itemsKey is wrong; \` +
            \`regenerate the extension.\`,
        );
      }
      break;
    }
    const pageItems = rawItems as T[];
    allResults.push(...pageItems);

    const pagination = data.pagination as Pagination | undefined;
    if (pagination?.total_pages !== undefined) {
      const current = pagination.page_number ?? page;
      if (current >= pagination.total_pages) break;
    } else {
      // No pagination metadata: a short page means we're done.
      if (pageItems.length < pageSize) break;
      if (page >= MAX_PAGES) {
        truncated = true;
        break;
      }
    }
    page++;
  }

  if (page > MAX_PAGES) truncated = true;

  return { results: allResults, truncated, totalFetched: allResults.length };
}
`;
}

