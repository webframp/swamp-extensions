/**
 * Extension generator — produces the complete directory structure for a
 * generated Griptape extension.
 *
 * For each service, generates:
 * - manifest.yaml
 * - deno.json
 * - README.md
 * - LICENSE.md (Apache-2.0)
 * - RELEASE_NOTES.md
 * - .swamp.yaml
 * - .gitignore
 * - extensions/models/griptape/{name}.ts
 * - extensions/models/griptape/{name}_test.ts
 * - extensions/models/griptape/_lib/api.ts (shared helper)
 */

import type { ServiceConfig } from "../config.ts";
import {
  GRIPTAPE_API_BASE,
  MAX_PAGES,
  OUTPUT_BASE,
  SWAMP_TESTING_VERSION,
} from "../config.ts";

/** Generate manifest.yaml content. Double-quoted name for ci-discover. */
export function generateManifest(
  config: ServiceConfig,
  version: string,
  modelFileName: string,
): string {
  return `manifestVersion: 1
name: "@webframp/griptape/${config.name}"
version: "${version}"
description: "${config.description}"
repository: "https://github.com/webframp/swamp-extensions"
models:
  - griptape/${modelFileName}
platforms:
  - linux-x86_64
  - linux-aarch64
  - darwin-x86_64
  - darwin-aarch64
additionalFiles:
  - README.md
  - LICENSE.md
labels:
${config.labels.map((l) => `  - ${l}`).join("\n")}
`;
}

/** Generate deno.json content. */
export function generateDenoJson(): string {
  return JSON.stringify(
    {
      compilerOptions: { strict: true },
      tasks: {
        check:
          "deno check extensions/models/griptape/*.ts extensions/models/griptape/_lib/*.ts",
        lint: "deno lint extensions/models/",
        fmt: "deno fmt extensions/models/",
        "fmt:check": "deno fmt --check extensions/models/",
        test: "deno test --allow-env --allow-net extensions/models/",
      },
      lint: {
        rules: {
          exclude: ["no-import-prefix"],
        },
      },
      imports: {
        "@systeminit/swamp-testing":
          `jsr:@systeminit/swamp-testing@${SWAMP_TESTING_VERSION}`,
      },
    },
    null,
    2,
  ) + "\n";
}

