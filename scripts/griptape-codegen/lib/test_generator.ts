/**
 * Test generator — produces HTTP-mock test files for generated Griptape models.
 *
 * Matches the Griptape runtime shape:
 * - No response envelope: single-resource endpoints return the entity directly.
 * - List endpoints return { <itemsKey>: [...], pagination: {...} }.
 * - The mock rewrites https://cloud.griptape.ai/api to the local server.
 *
 * Test fixtures are synthesized from the OpenAPI response schemas.
 */

import type { ClassifiedMethod } from "./method_classifier.ts";
import { sanitizeFieldName } from "./method_classifier.ts";
import type { SchemaObject } from "./schema_fetcher.ts";
import type { ServiceConfig } from "../config.ts";
import { GRIPTAPE_API_BASE } from "../config.ts";

/**
 * The value substituted for every path parameter in generated tests. Used in
 * the mock server's registered path, the path-param argument values, and the
 * delete fixture — defined once so they cannot drift.
 */
export const PATH_PARAM_TEST_VALUE = "test-id-123";

/** Generate a complete test file for a service. */
export function generateTestSource(
  config: ServiceConfig,
  methods: ClassifiedMethod[],
  modelFileName: string,
): string {
  const lines: string[] = [];

  lines.push(`// ${config.description} — Tests`);
  lines.push(
    `// Auto-generated by scripts/griptape-codegen — do not edit manually.`,
  );
  lines.push(`// SPDX-License-Identifier: Apache-2.0`);
  lines.push(``);
  lines.push(
    `import { assertEquals, assertExists } from "jsr:@std/assert@1.0.19";`,
  );
  lines.push(
    `import { createModelTestContext } from "@systeminit/swamp-testing";`,
  );
  lines.push(`import { model } from "./${modelFileName}.ts";`);
  lines.push(``);

  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(`// Model Export Structure Tests`);
  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(``);

  lines.push(`Deno.test("${config.name} model: has correct type", () => {`);
  lines.push(
    `  assertEquals(model.type, "@webframp/griptape/${config.name}");`,
  );
  lines.push(`});`);
  lines.push(``);

  lines.push(
    `Deno.test("${config.name} model: has valid version format", () => {`,
  );
  lines.push(`  const versionPattern = /^\\d{4}\\.\\d{2}\\.\\d{2}\\.\\d+$/;`);
  lines.push(`  assertEquals(versionPattern.test(model.version), true);`);
  lines.push(`});`);
  lines.push(``);

  lines.push(
    `Deno.test("${config.name} model: has globalArguments with apiKey", () => {`,
  );
  lines.push(`  assertExists(model.globalArguments);`);
  lines.push(`  const shape = model.globalArguments.shape;`);
  lines.push(`  assertExists(shape.apiKey);`);
  lines.push(`});`);
  lines.push(``);

  lines.push(`Deno.test("${config.name} model: has expected methods", () => {`);
  lines.push(`  assertExists(model.methods);`);
  for (const method of methods) {
    lines.push(`  assertExists(model.methods.${method.name});`);
  }
  lines.push(`});`);
  lines.push(``);

  const resources = methods
    .filter((m) => m.type !== "delete")
    .map(resourceNameFor);
  const uniqueResources = [...new Set(resources)];

  lines.push(
    `Deno.test("${config.name} model: has expected resources", () => {`,
  );
  lines.push(`  assertExists(model.resources);`);
  for (const r of uniqueResources) {
    lines.push(`  assertExists(model.resources["${r}"]);`);
  }
  lines.push(`});`);
  lines.push(``);

  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(`// Mock Griptape API Server`);
  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(``);
  lines.push(generateMockServer());
  lines.push(``);

  // One execution test per method type.
  const testedTypes = new Set<string>();
  for (const method of methods) {
    if (testedTypes.has(method.type)) continue;
    testedTypes.add(method.type);
    lines.push(generateExecutionTest(config, method));
    lines.push(``);
  }

  return lines.join("\n");
}

/** Mirror of method_classifier.resourceNameFor (kept local to avoid export churn). */
function resourceNameFor(method: ClassifiedMethod): string {
  const { name, type } = method;
  if (type === "list") return name.replace(/^list_/, "");
  return name.replace(
    /^(get|create|update|cancel|refresh|run|query|search|execute|start|send|save|allocate|renew|release|chat)_/,
    "",
  );
}

/** Generate the mock HTTP server helper. */
function generateMockServer(): string {
  return `interface MockResponse {
  body: unknown;
  itemsKey?: string;
  status?: number;
}

function startMockGtServer(
  responses: Record<string, MockResponse>,
): { url: string; server: Deno.HttpServer } {
  const server = Deno.serve({ port: 0, onListen() {} }, (req) => {
    const url = new URL(req.url);
    const path = url.pathname;

    for (const [pattern, spec] of Object.entries(responses)) {
      if (path.includes(pattern)) {
        const status = spec.status ?? 200;
        // 204/205 must have a null body.
        if (status === 204 || status === 205) {
          return new Response(null, { status });
        }
        if (spec.itemsKey) {
          return Response.json({
            [spec.itemsKey]: spec.body,
            pagination: {
              page_number: 1,
              page_size: 50,
              total_count: Array.isArray(spec.body) ? spec.body.length : 0,
              total_pages: 1,
            },
          }, { status });
        }
        return Response.json(spec.body, { status });
      }
    }

    return Response.json({ message: "Not found" }, { status: 404 });
  });

  const addr = server.addr as Deno.NetAddr;
  return { url: \`http://localhost:\${addr.port}\`, server };
}

function installFetchMock(mockUrl: string): () => void {
  const originalFetch = globalThis.fetch;
  globalThis.fetch = (input, init) => {
    const reqUrl = typeof input === "string" ? input : input.toString();
    const newUrl = reqUrl.replace("${GRIPTAPE_API_BASE}", mockUrl);
    return originalFetch(newUrl, init);
  };
  return () => {
    globalThis.fetch = originalFetch;
  };
}`;
}

/** Generate an execution test for a method. */
function generateExecutionTest(
  config: ServiceConfig,
  method: ClassifiedMethod,
): string {
  const globalArgs = { apiKey: "test-key" };
  const fixture = generateFixture(method);
  const pathPattern = extractPathPattern(method.operation.path);
  const testArgs = buildTestArgs(method);
  const execCast =
    `(model.methods as Record<string, { execute: (args: Record<string, unknown>, ctx: unknown) => Promise<{ dataHandles: unknown[] }> }>)`;
  const ctxDef =
    `definition: { id: "test-id", name: "test-${config.name}", version: 1, tags: {} },`;

  if (method.type === "list") {
    const itemsKey = method.operation.listItemsKey ?? "data";
    const argsStr = Object.keys(testArgs).length > 0
      ? JSON.stringify(testArgs)
      : "{}";
    return `Deno.test({
  name: "${config.name} model: ${method.name} fetches and writes resource",
  sanitizeResources: false,
  fn: async () => {
    const { url, server } = startMockGtServer({
      "${pathPattern}": { body: [${
      JSON.stringify(fixture)
    }], itemsKey: "${itemsKey}" },
    });
    const uninstall = installFetchMock(url);
    try {
      const { context, getWrittenResources } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        ${ctxDef}
      });
      const result = await ${execCast}.${method.name}.execute(${argsStr}, context);
      assertEquals(result.dataHandles.length, 1);
      assertEquals(getWrittenResources().length, 1);
    } finally {
      uninstall();
      await server.shutdown();
    }
  },
});`;
  }

  if (method.type === "get") {
    return `Deno.test({
  name: "${config.name} model: ${method.name} fetches and writes resource",
  sanitizeResources: false,
  fn: async () => {
    const { url, server } = startMockGtServer({
      "${pathPattern}": { body: ${JSON.stringify(fixture)} },
    });
    const uninstall = installFetchMock(url);
    try {
      const { context, getWrittenResources } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        ${ctxDef}
      });
      const result = await ${execCast}.${method.name}.execute(${
      JSON.stringify(testArgs)
    }, context);
      assertEquals(result.dataHandles.length, 1);
      assertEquals(getWrittenResources().length, 1);
    } finally {
      uninstall();
      await server.shutdown();
    }
  },
});`;
  }

  if (method.type === "delete") {
    return `Deno.test({
  name: "${config.name} model: ${method.name} executes successfully",
  sanitizeResources: false,
  fn: async () => {
    const { url, server } = startMockGtServer({
      "${pathPattern}": { body: {}, status: 204 },
    });
    const uninstall = installFetchMock(url);
    try {
      const { context } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        ${ctxDef}
      });
      const result = await ${execCast}.${method.name}.execute(${
      JSON.stringify(testArgs)
    }, context);
      assertEquals(result.dataHandles.length, 0);
    } finally {
      uninstall();
      await server.shutdown();
    }
  },
});`;
  }

  // create / update / action — path params win over the fixture so a body
  // field sharing a path-param name cannot rewrite the request URL.
  const idField = method.type === "create"
    ? entityIdFieldForTest(method)
    : null;
  const responseBody = idField ? { [idField]: "new-123", ...fixture } : fixture;
  const callArgs = buildFinalTestArgs(method, fixture);
  const verb = method.type === "create" ? "creates" : "executes";
  return `Deno.test({
  name: "${config.name} model: ${method.name} ${verb} and writes resource",
  sanitizeResources: false,
  fn: async () => {
    const { url, server } = startMockGtServer({
      "${pathPattern}": { body: ${JSON.stringify(responseBody)} },
    });
    const uninstall = installFetchMock(url);
    try {
      const { context, getWrittenResources } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        ${ctxDef}
      });
      const result = await ${execCast}.${method.name}.execute(${
    JSON.stringify(callArgs)
  }, context);
      assertEquals(result.dataHandles.length, 1);
      assertEquals(getWrittenResources().length, 1);
    } finally {
      uninstall();
      await server.shutdown();
    }
  },
});`;
}

/** Mirror of method_classifier.entityIdCandidates for building create fixtures. */
/**
 * The response id field to seed a create test fixture with, mirroring the
 * runtime resolution order in method_classifier.entityIdCandidates:
 *   1. the resource-id path param (last URL-template placeholder), when the
 *      create path ends in one;
 *   2. `<singular-resource>_id`;
 *   3. the entity's actual own id-shaped field from the response schema
 *      (so a resource like `model` whose id is `model_config_id` seeds the
 *      fixture with the field the runtime scan will actually find, exercising
 *      the primary path rather than a dead fallback);
 *   4. `id`.
 */
function entityIdFieldForTest(method: ClassifiedMethod): string {
  const path = method.operation.path;
  const endsWithParam = /\{[^}]+\}\/?$/.test(path);
  if (endsWithParam) {
    const matches = [...path.matchAll(/\{([^}]+)\}/g)];
    const lastName = matches[matches.length - 1]?.[1];
    if (lastName && /_id$/.test(lastName) && lastName !== "organization_id") {
      return lastName;
    }
  }

  const resource = resourceNameFor(method).replace(/-/g, "_");
  const singular = resource.endsWith("s") ? resource.slice(0, -1) : resource;
  const derived = `${singular}_id`;

  // If the response schema declares the derived key, use it. Otherwise pick the
  // entity's own id-shaped field (not organization_id) so the fixture forces the
  // runtime scan path the way production will hit it.
  const props = method.operation.responseSchema?.properties;
  if (props) {
    if (props[derived]) return derived;
    for (const key of Object.keys(props)) {
      if (/(^|_)id$/.test(key) && key !== "organization_id") return key;
    }
  }
  return derived;
}

/** Generate a synthetic fixture from a response schema. */
function generateFixture(method: ClassifiedMethod): Record<string, unknown> {
  const schema = method.operation.responseSchema;
  if (!schema) return { id: "fixture-123" };
  const value = synthesizeValue(schema);
  return (value && typeof value === "object")
    ? value as Record<string, unknown>
    : { value };
}

/** Synthesize a value matching a schema (for test fixtures). */
function synthesizeValue(schema: SchemaObject, depth = 0): unknown {
  if (depth > 4) return null;
  if (schema.example !== undefined) return schema.example;
  if (schema.enum) return schema.enum[0];

  switch (schema.type) {
    case "string":
      if (schema.format === "date-time") return "2024-01-01T00:00:00Z";
      if (schema.format === "uri" || schema.format === "url") {
        return "https://example.com";
      }
      return "test-value";
    case "number":
    case "integer":
      return schema.minimum ?? 1;
    case "boolean":
      return true;
    case "array":
      return schema.items ? [synthesizeValue(schema.items, depth + 1)] : [];
    case "object":
      if (schema.properties) {
        const obj: Record<string, unknown> = {};
        for (const [name, prop] of Object.entries(schema.properties)) {
          obj[name] = synthesizeValue(prop, depth + 1);
        }
        return obj;
      }
      return {};
    default:
      return null;
  }
}

/**
 * Extract a path pattern for mock server matching: replace path params with the
 * fixed test value so the pattern matches what the model actually requests.
 */
export function extractPathPattern(path: string): string {
  return path
    .replace(/\{[^}]+\}/g, PATH_PARAM_TEST_VALUE)
    .replace(/\/$/, "");
}

/** Build test args containing path param values matching the mock pattern. */
function buildTestArgs(method: ClassifiedMethod): Record<string, unknown> {
  const args: Record<string, unknown> = {};
  for (const p of method.operation.pathParams) {
    args[sanitizeFieldName(p.name)] = PATH_PARAM_TEST_VALUE;
  }
  return args;
}

/**
 * Merge a request-body fixture with path-param values, path params winning.
 * Exported for direct unit testing.
 */
export function buildFinalTestArgs(
  method: ClassifiedMethod,
  fixture: Record<string, unknown>,
): Record<string, unknown> {
  return { ...fixture, ...buildTestArgs(method) };
}
