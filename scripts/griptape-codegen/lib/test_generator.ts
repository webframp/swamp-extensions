/**
 * The response id field to seed a create test fixture with, mirroring the
 * runtime resolution order in method_classifier.entityIdCandidates:
 *   1. the resource-id path param (last URL-template placeholder), when the
 *      create path ends in one;
 *   2. `<singular-resource>_id`;
 *   3. the entity's actual own id-shaped field from the response schema
 *      (so a resource like `model` whose id is `model_config_id` seeds the
 *      fixture with the field the runtime scan will actually find, exercising
 *      the primary path rather than a dead fallback);
 *   4. `id`.
 */
function entityIdFieldForTest(method: ClassifiedMethod): string {
  const path = method.operation.path;
  const endsWithParam = /\{[^}]+\}\/?$/.test(path);
  if (endsWithParam) {
    const matches = [...path.matchAll(/\{([^}]+)\}/g)];
    const lastName = matches[matches.length - 1]?.[1];
    if (lastName && /_id$/.test(lastName) && lastName !== "organization_id") {
      return lastName;
    }
  }

  const resource = resourceNameFor(method).replace(/-/g, "_");
  const singular = resource.endsWith("s") ? resource.slice(0, -1) : resource;
  const derived = `${singular}_id`;

  // If the response schema declares the derived key, use it. Otherwise pick the
  // entity's own id-shaped field (not organization_id) so the fixture forces the
  // runtime scan path the way production will hit it.
  const props = method.operation.responseSchema?.properties;
  if (props) {
    if (props[derived]) return derived;
    for (const key of Object.keys(props)) {
      if (/(^|_)id$/.test(key) && key !== "organization_id") return key;
    }
  }
  return derived;
}

/** Generate a synthetic fixture from a response schema. */
function generateFixture(method: ClassifiedMethod): Record<string, unknown> {
  const schema = method.operation.responseSchema;
  if (!schema) return { id: "fixture-123" };
  const value = synthesizeValue(schema);
  return (value && typeof value === "object")
    ? value as Record<string, unknown>
    : { value };
}

/** Synthesize a value matching a schema (for test fixtures). */
export function synthesizeValue(schema: SchemaObject, depth = 0): unknown {
  if (depth > 4) return null;
  if (schema.example !== undefined) return schema.example;
  if (schema.enum) return schema.enum[0];

  switch (schema.type) {
    case "string":
      if (schema.format === "date-time") return "2024-01-01T00:00:00Z";
      if (schema.format === "uri" || schema.format === "url") {
        return "https://example.com";
      }
      return "test-value";
    case "number":
    case "integer":
      return schema.minimum ?? 1;
    case "boolean":
      return true;
    case "array":
      return schema.items ? [synthesizeValue(schema.items, depth + 1)] : [];
    case "object":
      if (schema.properties) {
        const obj: Record<string, unknown> = {};
        for (const [name, prop] of Object.entries(schema.properties)) {
          obj[name] = synthesizeValue(prop, depth + 1);
        }
        return obj;
      }
      return {};
    default:
      return null;
  }
}

/**
 * Extract the concrete request path for mock server matching: replace path
 * params with the fixed test value so it matches what the model actually
 * requests.
 */
export function extractPathPattern(path: string): string {
  return path
    .replace(/\{[^}]+\}/g, PATH_PARAM_TEST_VALUE)
    .replace(/\/$/, "");
}
