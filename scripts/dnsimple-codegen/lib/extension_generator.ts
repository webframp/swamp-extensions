/**
 * Extension generator — produces the complete directory structure for a generated extension.
 *
 * For each service, generates:
 * - manifest.yaml
 * - deno.json
 * - README.md
 * - LICENSE.md (Apache-2.0 boilerplate, identical across every extension in this repo)
 * - RELEASE_NOTES.md
 * - .swamp.yaml
 * - .gitignore
 * - extensions/models/dnsimple/{name}.ts
 * - extensions/models/dnsimple/{name}_test.ts
 * - extensions/models/dnsimple/_lib/api.ts (shared helper, copied from lib/runtime/api.ts)
 * - extensions/models/dnsimple/_lib/api_test.ts (its tests, copied from lib/runtime/api_test.ts)
 */

import type { ServiceConfig } from "../config.ts";
import {
  BILLABLE_OPERATIONS,
  OUTPUT_BASE,
  SENSITIVE_ARG_FIELDS,
  SENSITIVE_RESPONSE_FIELDS,
  SWAMP_TESTING_VERSION,
} from "../config.ts";

/** Generate manifest.yaml content */
export function generateManifest(
  config: ServiceConfig,
  version: string,
  modelFileName: string,
): string {
  return `manifestVersion: 1
name: "@webframp/dnsimple/${config.name}"
license: Apache-2.0
version: "${version}"
description: "${config.description}"
repository: "https://github.com/webframp/swamp-extensions"
models:
  - dnsimple/${modelFileName}
platforms:
  - linux-x86_64
  - linux-aarch64
  - darwin-x86_64
  - darwin-aarch64
additionalFiles:
  - README.md
  - LICENSE.md
labels:
${config.labels.map((l) => `  - ${l}`).join("\n")}
`;
}

/** Generate deno.json content */
export function generateDenoJson(): string {
  return JSON.stringify(
    {
      compilerOptions: { strict: true },
      tasks: {
        check:
          "deno check extensions/models/dnsimple/*.ts extensions/models/dnsimple/_lib/*.ts",
        lint: "deno lint extensions/models/",
        fmt: "deno fmt extensions/models/",
        "fmt:check": "deno fmt --check extensions/models/",
        test: "deno test --allow-env --allow-net extensions/models/",
      },
      lint: {
        rules: {
          exclude: ["no-import-prefix"],
        },
      },
      imports: {
        "@swamp-club/swamp-testing":
          `jsr:@swamp-club/swamp-testing@${SWAMP_TESTING_VERSION}`,
      },
    },
    null,
    2,
  ) + "\n";
}

/** A method as the README needs it; `operation` identifies returned secrets. */
export interface ReadmeMethod {
  name: string;
  description: string;
  type: string;
  operation?: { operationId: string; accountScoped?: boolean };
}

/** Generate README.md for the extension */
export function generateReadme(
  config: ServiceConfig,
  methods: ReadmeMethod[],
): string {
  return `# @webframp/dnsimple/${config.name}

${config.description}

Auto-generated by \`scripts/dnsimple-codegen\` from DNSimple's API v2 OpenAPI specification.

## Usage

\`\`\`bash
swamp extension pull @webframp/dnsimple/${config.name}
\`\`\`

## Credentials

Store the DNSimple access token in a swamp vault and reference it with a
\`vault.get\` expression; never pass the literal value. Any vault type works —
\`local_encryption\`, or an extension such as \`@webframp/pass\`,
\`@webframp/gopass\`, \`@webframp/hashicorp-vault\` or
\`@webframp/macos-keychain\`.

\`\`\`bash
swamp vault create local_encryption dnsimple   # once, if you have no vault yet
swamp vault put dnsimple API_TOKEN             # prompts; the value never reaches shell history
swamp model create @webframp/dnsimple/${config.name} dnsimple-${config.name} \\
  --global-arg 'apiToken=\${{ vault.get("dnsimple", "API_TOKEN") }}' \\
  --global-arg accountId=<account id from whoami>
\`\`\`

If \`apiToken\` is unset, the model reads the \`DNSIMPLE_TOKEN\` environment
variable as a fallback. That value is not redacted from swamp output and is not
recommended.

## Account and environment

Account-scoped methods substitute the \`accountId\` global argument for the
\`/{account}\` path segment. It stays optional so \`whoami\` and \`list_accounts\`
(in \`@webframp/dnsimple/account\`) can run before you know the ID; an
account-scoped method without it fails before any request goes out.

\`environment\` is \`production\` by default. Set \`--global-arg environment=sandbox\`
to use DNSimple's sandbox, which has its own accounts and tokens.
${billableParagraph(methods)}${contactDataSection(config)}${
    vaultRequirementParagraph(methods)
  }${secretsSection(methods)}
## Methods

| Method | Description |
|--------|-------------|
${
    methods.map((m) =>
      `| \`${m.name}\` | ${m.description.replace(/\|/g, "\\|")} |`
    ).join("\n")
  }

## Development

\`\`\`bash
cd ${OUTPUT_BASE.replace(/^(\.\.\/)+/, "")}/${config.name}
deno task check
deno task lint
deno task fmt
deno task test
\`\`\`

## License

Apache-2.0 — see [LICENSE.md](LICENSE.md).
`;
}

/**
 * The README's "Contact data" section, or "" for services that do not return
 * registrant details. Contact fields are deliberately not marked sensitive.
 */
function contactDataSection(config: ServiceConfig): string {
  if (!config.storesContactData) return "";
  return `
## Contact data

Registrant contact details (names, email addresses, phone numbers and postal
addresses) are required to manage a domain, so this extension stores them as
ordinary swamp data and does not mark them sensitive. Sensitive fields move to
a vault and leave only a reference, which would make contact records unreadable
to expressions and reports. The access controls of the datastore that holds
your swamp data are the boundary for this data. Each resource keeps a bounded
number of versions (\`garbageCollection\`), so older copies are pruned.
`;
}

/** The paragraph warning that some methods charge the account, or "". */
function billableParagraph(methods: ReadmeMethod[]): string {
  const billable = methods.filter((m) =>
    m.operation && BILLABLE_OPERATIONS.includes(m.operation.operationId)
  );
  if (billable.length === 0) return "";
  return `
## Billable methods

These methods charge the DNSimple account. Their descriptions open with
"Billable:". Try them against the sandbox first.

${billable.map((m) => `- \`${m.name}\``).join("\n")}
`;
}

/** Methods whose response carries secrets, with the fields marked sensitive. */
function secretReturningMethods(
  methods: ReadmeMethod[],
): { name: string; fields: string[] }[] {
  return methods.flatMap((m) => {
    const fields = m.operation
      ? SENSITIVE_RESPONSE_FIELDS[m.operation.operationId]
      : undefined;
    return fields && m.type !== "delete" ? [{ name: m.name, fields }] : [];
  });
}

/** Methods that take a secret argument, with the fields marked sensitive. */
function secretTakingMethods(
  methods: ReadmeMethod[],
): { name: string; fields: string[] }[] {
  return methods.flatMap((m) => {
    const fields = m.operation
      ? SENSITIVE_ARG_FIELDS[m.operation.operationId]
      : undefined;
    return fields ? [{ name: m.name, fields }] : [];
  });
}

/**
 * Method names swamp treats as reads by name alone (its `inferMethodKind`).
 * Every other method is a possible write, and swamp refuses to run one on a
 * model with sensitive resource fields until a vault exists.
 */
const SWAMP_READ_NAMES = new Set([
  "get",
  "read",
  "describe",
  "show",
  "list",
  "search",
  "find",
]);

/**
 * True when a resource of the model declares a sensitive field, which makes
 * swamp demand a vault before it runs the model's methods.
 */
export function modelRequiresVault(methods: ReadmeMethod[]): boolean {
  return secretReturningMethods(methods).length > 0;
}

/** The sentence stating which of a model's methods need a vault to exist. */
function vaultRefusalSentence(methods: ReadmeMethod[]): string {
  const reads = methods.map((m) => m.name).filter((n) =>
    SWAMP_READ_NAMES.has(n.toLowerCase())
  );
  const create = "(`swamp vault create local_encryption dnsimple`)";
  if (reads.length === 0) {
    return `Because the model declares these fields sensitive, swamp refuses to
run any of its methods, reads included, until a vault exists ${create}.`;
  }
  return `Because the model declares these fields sensitive, swamp refuses to
run any of its methods except ${
    reads.map((n) => `\`${n}\``).join(" and ")
  } until a vault exists ${create}; swamp treats a method of ${
    reads.length === 1 ? "that name" : "those names"
  } as a read.`;
}

/**
 * Credentials-section paragraph stating that the model needs a vault for the
 * secrets it returns, or "" when no resource declares one.
 */
function vaultRequirementParagraph(methods: ReadmeMethod[]): string {
  if (!modelRequiresVault(methods)) return "";
  return `
Some methods return secrets, which swamp stores in a vault (see
[Secrets](#secrets)). ${vaultRefusalSentence(methods)}
`;
}

/** The README's "Secrets" section, or "" when no method handles a secret. */
function secretsSection(methods: ReadmeMethod[]): string {
  const returning = secretReturningMethods(methods);
  const taking = secretTakingMethods(methods);
  if (returning.length === 0 && taking.length === 0) return "";
  const returnsText = returning.length === 0 ? "" : `
These methods return a secret. The resource marks each listed field
sensitive, so swamp stores the value in a vault and the resource keeps only a
\`vault.get(...)\` reference. ${vaultRefusalSentence(methods)} The stored
reference names the vault and key that hold the secret; use that
\`vault.get(...)\` expression wherever another model needs it.

| Method | Fields stored in a vault |
|--------|--------------------------|
${
    returning.map((m) =>
      `| \`${m.name}\` | ${m.fields.map((f) => `\`${f}\``).join(", ")} |`
    ).join("\n")
  }
`;
  const takesText = taking.length === 0 ? "" : `
These methods take a secret argument. The argument is marked sensitive and is
left out of the receipt the method writes.

| Method | Sensitive arguments |
|--------|---------------------|
${
    taking.map((m) =>
      `| \`${m.name}\` | ${m.fields.map((f) => `\`${f}\``).join(", ")} |`
    ).join("\n")
  }
`;
  return `
## Secrets
${returnsText}${takesText}`;
}

/** Generate RELEASE_NOTES.md */
export function generateReleaseNotes(
  config: ServiceConfig,
  version: string,
  methodCount: number,
  body?: string,
): string {
  const text = body ??
    `**Added:** Initial code-generated release of @webframp/dnsimple/${config.name} with ${methodCount} methods covering the DNSimple ${
      config.name.replace(/-/g, " ")
    } API surface.`;
  return `## ${version}

${text.trimEnd()}
`;
}

/**
 * Generate .swamp.yaml, preserving an existing repoId.
 *
 * swamp mints `repoId` lazily into the marker on first invocation in a
 * directory; the generator never creates one. Regenerating with a fresh
 * marker would DELETE the repoId, so any existing value is carried forward.
 */
export function generateSwampYaml(existing?: string): string {
  let repoIdLine = "";
  if (existing) {
    const match = existing.match(/^repoId:\s*(\S+)\s*$/m);
    if (match) repoIdLine = `repoId: ${match[1]}\n`;
  }
  return `# Swamp repository marker
# Generated by scripts/dnsimple-codegen
repoVersion: 1
${repoIdLine}`;
}

/** Generate .gitignore */
export function generateGitignore(): string {
  return `.swamp/
CLAUDE.md
AGENTS.md
`;
}

/** Read a runtime source file that ships verbatim into every extension. */
function readRuntime(name: string): string {
  return Deno.readTextFileSync(new URL(`./runtime/${name}`, import.meta.url));
}

/**
 * Generate the shared _lib/api.ts helper. It is the type-checked, tested
 * `lib/runtime/api.ts`, copied verbatim, so the generator and the generated
 * code cannot drift apart.
 */
export function generateApiLib(): string {
  return readRuntime("api.ts");
}

/** Generate _lib/api_test.ts: the helper's tests, copied from lib/runtime. */
export function generateApiLibTest(): string {
  return readRuntime("api_test.ts");
}

