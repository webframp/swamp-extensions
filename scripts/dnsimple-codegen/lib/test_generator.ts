/**
 * The emitted helper that finds the paths swamp vaults in a resource schema,
 * matching swamp's extractSensitiveFields: plain object shapes only, seen
 * through optional, nullable and default wrappers and no others.
 */
export function swampSensitivePathsHelper(): string {
  return `/**
 * Paths swamp vaults in a resource schema: fields carrying
 * .meta({ sensitive: true }) on the field or on an optional, nullable or
 * default wrapper around it, found by walking plain object shapes only (swamp
 * does not enter arrays or unions, or see through readonly or catch).
 */
function swampSensitivePaths(schema: unknown, prefix = ""): string[] {
  // deno-lint-ignore no-explicit-any
  const inner = (s: any): any =>
    ["optional", "nullable", "default"].includes(s?._zod?.def?.type)
      ? s._zod.def.innerType
      : undefined;
  // deno-lint-ignore no-explicit-any
  const unwrap = (s: any): any => {
    while (inner(s)) s = inner(s);
    return s;
  };
  // deno-lint-ignore no-explicit-any
  const isMarked = (s: any): boolean => {
    for (let cur = s; cur; cur = inner(cur)) {
      if (cur.meta?.()?.sensitive === true) return true;
    }
    return false;
  };
  const obj = unwrap(schema);
  if (obj?._zod?.def?.type !== "object") return [];
  const out: string[] = [];
  for (const [key, field] of Object.entries(obj._zod.def.shape)) {
    const path = prefix ? prefix + "." + key : key;
    if (isMarked(field)) out.push(path);
    out.push(...swampSensitivePaths(field, path));
  }
  return out.sort();
}`;
}

/**
 * Test that a method's secrets reach swamp marked sensitive.
 *
 * swamp's data writer (not the model) moves each field the resource schema
 * marks \`.meta({ sensitive: true })\` into a vault and persists a
 * \`vault.get(...)\` reference instead; createModelTestContext captures the
 * pre-persistence data. So the test pins the three things the model owns: the
 * schema marks exactly the configured fields, the method hands swamp the
 * secret rather than dropping it, and replacing the marked fields with vault
 * references — what swamp persists — leaves no plaintext anywhere in the
 * resource and still validates against the schema.
 */
function generateSensitiveFieldTest(
  config: ServiceConfig,
  method: ClassifiedMethod,
  fields: string[],
): string {
  const args = buildMethodArgs(method);
  const plaintext: Record<string, string> = {};
  for (const f of fields) plaintext[f] = `plaintext-secret-${f}`;
  const fixture = generateFixture(method) as Record<string, unknown>;
  const body = { data: { ...fixture, ...plaintext } };
  const sorted = [...fields].sort();
  const routes = `      ${JSON.stringify(routeKey(method))}: ${
    JSON.stringify({ body })
  },`;
  const resource = method.resource!;
  return testCase(
    `${config.name} model: ${method.name} marks ${
      sorted.join(", ")
    } sensitive so swamp stores them in a vault`,
    routes,
    `      const plaintext = ${JSON.stringify(plaintext)};
      await run(${JSON.stringify(method.name)}, ${
      JSON.stringify(args)
    }, context);

      const schema = model.resources["${resource}"].schema;
      const marked = swampSensitivePaths(schema);
      assertEquals(marked, ${JSON.stringify(sorted)});

      const resources = getWrittenResources();
      assertEquals(resources.length, 1);
      const data = resources[0].data as Record<string, unknown>;
      for (const [field, value] of Object.entries(plaintext)) {
        // Handed to swamp, which vaults it — not dropped.
        assertEquals(data[field], value);
      }

      // What swamp persists: each marked value replaced by a vault reference.
      const persisted = structuredClone(data) as Record<string, unknown>;
      for (const field of marked) {
        const keys = field.split(".");
        let holder: unknown = persisted;
        for (const key of keys.slice(0, -1)) {
          holder = (holder as Record<string, unknown> | undefined)?.[key];
        }
        if (holder !== null && typeof holder === "object") {
          (holder as Record<string, unknown>)[keys[keys.length - 1]] =
            "\${{ vault.get('test-vault', '${config.name}/${resource}/" + field + "') }}";
        }
      }
      const stored = JSON.stringify(persisted);
      for (const value of Object.values(plaintext)) {
        assertEquals(stored.includes(value), false);
      }
      for (const field of ${JSON.stringify(sorted)}) {
        assertEquals(String(persisted[field]).startsWith("\${{ vault.get("), true);
      }
      schema.parse(persisted);`,
    {},
  );
}

