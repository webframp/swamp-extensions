/**
 * Test generator — produces test files for generated models.
 *
 * Each generated model test file covers:
 * - Model structure (type, version, global arguments, methods, resources)
 * - One mock-server test per method, asserting the HTTP method, path, query,
 *   body and bearer token that went out and the resource that came back
 * - A two-page list and a list truncated at the page cap
 * - A `204` action receipt
 * - The missing-`accountId` error
 * - The repository's sensitive walk for fields swamp vaults
 *
 * The mock server speaks DNSimple's envelope: `{ data }` for a single item,
 * `{ data: [...], pagination }` for a list, and an empty `204`. Fixtures are
 * synthesized from the OpenAPI response schemas.
 */

import {
  argFields,
  bodyShape,
  type ClassifiedMethod,
  sanitizeFieldName,
  sensitiveArgFields,
} from "./method_classifier.ts";
import type { SchemaObject } from "./schema_fetcher.ts";
import {
  MAX_PAGES,
  SENSITIVE_RESPONSE_FIELDS,
  type ServiceConfig,
  ZOD_VERSION,
} from "../config.ts";

