/**
 * Test generator — produces test files for generated Snyk models.
 *
 * Generates tests matching the swamp extension test pattern:
 * - Model structure tests (type, version, methods, resources)
 * - Mock HTTP server tests (one per method type)
 *
 * Uses JSON:API mock responses (data/links envelope).
 */

import type { ClassifiedMethod } from "./method_classifier.ts";
import {
  resourceNameOf,
  secretArgumentPaths,
  secretListItemFields,
  secretResponseFields,
} from "./method_classifier.ts";
import { isSensitiveFieldName } from "./type_mapper.ts";
import type { SchemaObject } from "./schema_fetcher.ts";
import type { ServiceConfig } from "../config.ts";

/** Generate a complete test file for a service */
export function generateTestSource(
  config: ServiceConfig,
  methods: ClassifiedMethod[],
  modelFileName: string,
): string {
  const lines: string[] = [];

  lines.push(`// ${config.description} — Tests`);
  lines.push(
    `// Auto-generated by scripts/snyk-codegen — do not edit manually.`,
  );
  lines.push(`// SPDX-License-Identifier: Apache-2.0`);
  lines.push(``);
  lines.push(
    `import { assertEquals, assertExists } from "jsr:@std/assert@1.0.19";`,
  );
  lines.push(
    `import { createModelTestContext } from "@swamp-club/swamp-testing";`,
  );
  lines.push(`import { model } from "./${modelFileName}.ts";`);
  lines.push(``);

  // Model structure tests
  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(`// Model Export Structure Tests`);
  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(``);

  lines.push(`Deno.test("${config.name} model: has correct type", () => {`);
  lines.push(
    `  assertEquals(model.type, "@webframp/snyk/${config.name}");`,
  );
  lines.push(`});`);
  lines.push(``);

  lines.push(
    `Deno.test("${config.name} model: has valid version format", () => {`,
  );
  lines.push(`  const versionPattern = /^\\d{4}\\.\\d{2}\\.\\d{2}\\.\\d+$/;`);
  lines.push(`  assertEquals(versionPattern.test(model.version), true);`);
  lines.push(`});`);
  lines.push(``);

  lines.push(
    `Deno.test("${config.name} model: has globalArguments with apiToken", () => {`,
  );
  lines.push(`  assertExists(model.globalArguments);`);
  lines.push(`  const shape = model.globalArguments.shape;`);
  lines.push(`  assertExists(shape.apiToken);`);
  if (config.scope === "org") {
    lines.push(`  assertExists(shape.orgId);`);
  } else if (config.scope === "group") {
    lines.push(`  assertExists(shape.groupId);`);
  }
  lines.push(`  assertExists(shape.version);`);
  lines.push(`});`);
  lines.push(``);

  // Methods existence tests
  lines.push(
    `Deno.test("${config.name} model: has expected methods", () => {`,
  );
  lines.push(`  assertExists(model.methods);`);
  for (const method of methods) {
    lines.push(`  assertExists(model.methods.${method.name});`);
  }
  lines.push(`});`);
  lines.push(``);

  // Resources existence tests
  const resources = methods
    .filter((m) => m.type !== "delete")
    .map((m) => {
      return resourceNameOf(m);
    });
  const uniqueResources = [...new Set(resources)];

  lines.push(
    `Deno.test("${config.name} model: has expected resources", () => {`,
  );
  lines.push(`  assertExists(model.resources);`);
  for (const r of uniqueResources) {
    lines.push(`  assertExists(model.resources["${r}"]);`);
  }
  lines.push(`});`);
  lines.push(``);

  // Mock server + execution tests
  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(`// Mock Snyk API Server`);
  lines.push(
    `// ---------------------------------------------------------------------------`,
  );
  lines.push(``);
  lines.push(generateMockServer());
  lines.push(``);
  // Secret-handling helpers only when a method needs them, or deno lint
  // rejects the unused functions.
  const needsSecretHelpers = methods.some((m) =>
    secretResponseFields(m).length > 0 || secretArgumentPaths(m).length > 0
  );
  if (needsSecretHelpers) {
    lines.push(generateSecretHelpers());
    lines.push(``);
  }

  // Every method gets its own execute test asserting the request it sends
  // (verb, exact path, query parameters, body) and the resource it writes. A
  // method that was never executed could ship with a wrong path or verb and
  // still pass an existence check. Method names are unique per service, so
  // test names cannot collide.
  for (const method of methods) {
    lines.push(generateExecutionTest(config, method));
    lines.push(``);
  }

  // One error-path test per service: a 5xx must throw, not silently succeed.
  if (methods.length > 0) {
    lines.push(generateErrorTest(config, methods[0]));
    lines.push(``);
  }

  return lines.join("\n");
}

/** Generate the mock HTTP server for Snyk JSON:API */
function generateMockServer(): string {
  return `interface CapturedRequest {
  method: string;
  path: string;
  search: string;
  headers: Record<string, string>;
  body: unknown;
}

interface MockRoute {
  /** JSON:API primary data. Omit with a 202/204 status for an empty body. */
  data?: unknown;
  isCollection?: boolean;
  status?: number;
}

/**
 * Routes are keyed by exact "METHOD /path", so a method that calls the wrong
 * verb or path gets a 404 instead of a lucky substring match.
 */
function startMockSnykServer(
  routes: Record<string, MockRoute>,
): { url: string; server: Deno.HttpServer; requests: CapturedRequest[] } {
  const requests: CapturedRequest[] = [];
  const server = Deno.serve({ port: 0, onListen() {} }, async (req) => {
    const url = new URL(req.url);
    const path = url.pathname;

    // Capture the request (headers, method, path, query, parsed body).
    let reqBody: unknown = null;
    if (req.body) {
      const text = await req.text();
      if (text) {
        try {
          reqBody = JSON.parse(text);
        } catch {
          reqBody = text;
        }
      }
    }
    requests.push({
      method: req.method,
      path,
      search: url.search,
      headers: Object.fromEntries(req.headers),
      body: reqBody,
    });

    const route = routes[\`\${req.method} \${path}\`];
    if (route) {
      if (route.data === undefined) {
        return new Response(null, { status: route.status ?? 204 });
      }
      const body = route.isCollection
        ? {
            data: Array.isArray(route.data) ? route.data : [route.data],
            jsonapi: { version: "1.0" },
            links: { self: path, next: null },
          }
        : {
            data: route.data,
            jsonapi: { version: "1.0" },
            links: { self: path },
          };
      return Response.json(body, {
        status: route.status ?? 200,
        headers: { "content-type": "application/vnd.api+json" },
      });
    }

    return new Response(JSON.stringify({
      jsonapi: { version: "1.0" },
      errors: [{ status: "404", detail: \`No mock route for \${req.method} \${path}\` }],
    }), { status: 404, headers: { "content-type": "application/vnd.api+json" } });
  });

  const addr = server.addr as Deno.NetAddr;
  return { url: \`http://localhost:\${addr.port}\`, server, requests };
}

/** Written data must satisfy the schema the model declares for its resource. */
function assertValidResource(specName: string, data: unknown): void {
  const resources = model.resources as Record<
    string,
    { schema: { safeParse: (d: unknown) => { success: boolean } } }
  >;
  assertEquals(
    resources[specName].schema.safeParse(data).success,
    true,
    \`data written to \${specName} does not satisfy its resource schema\`,
  );
}

function installFetchMock(mockUrl: string): () => void {
  const originalFetch = globalThis.fetch;
  globalThis.fetch = (input, init) => {
    const reqUrl = typeof input === "string" ? input : input.toString();
    const newUrl = reqUrl.replace("https://api.snyk.io/rest", mockUrl);
    return originalFetch(newUrl, init);
  };
  return () => {
    globalThis.fetch = originalFetch;
  };
}`;
}

/**
 * Test helpers that check a model marks secrets the way swamp needs: swamp
 * vaults a resource field marked sensitive by walking object shapes, through
 * optional/nullable/default wrappers only (its extractSensitiveFields), and
 * replaces the value with a vault reference before it persists the resource.
 */
export function generateSecretHelpers(): string {
  return `interface ZodNode {
  _zod: {
    def: {
      type: string;
      innerType?: ZodNode;
      shape?: Record<string, ZodNode>;
    };
  };
  meta(): Record<string, unknown> | undefined;
}

const ZOD_WRAPPERS = new Set(["optional", "nullable", "default"]);

/** True when the field, or any wrapper level of it, is marked sensitive. */
function markedSensitive(node: ZodNode): boolean {
  for (let n: ZodNode | undefined = node; n;) {
    if (n.meta()?.sensitive === true) return true;
    n = ZOD_WRAPPERS.has(n._zod.def.type) ? n._zod.def.innerType : undefined;
  }
  return false;
}

/**
 * Paths swamp moves into a vault when it writes data with this schema. Like
 * swamp, it walks object shapes only: not arrays, not unions.
 */
function vaultedPaths(schema: unknown, prefix = ""): string[] {
  let node = schema as ZodNode;
  while (ZOD_WRAPPERS.has(node._zod.def.type) && node._zod.def.innerType) {
    node = node._zod.def.innerType;
  }
  if (node._zod.def.type !== "object") return [];
  const out: string[] = [];
  for (const [key, field] of Object.entries(node._zod.def.shape ?? {})) {
    const path = prefix ? \`\${prefix}.\${key}\` : key;
    if (markedSensitive(field)) out.push(path);
    out.push(...vaultedPaths(field, path));
  }
  return out;
}

/**
 * The written resource carries each secret, every one is marked sensitive on
 * the resource schema, and after swamp's vault substitution no secret value
 * is left in what it persists.
 */
function assertSecretsVaulted(
  specName: string,
  data: unknown,
  fields: string[],
): void {
  const resources = model.resources as Record<string, { schema: unknown }>;
  const paths = vaultedPaths(resources[specName].schema);
  const written = data as Record<string, unknown>;
  for (const field of fields) {
    assertEquals(written[field], \`fixture-\${field}\`);
    assertEquals(
      paths.includes(field),
      true,
      \`\${field} is not marked sensitive on \${specName}\`,
    );
  }
  const persisted = structuredClone(written);
  for (const path of paths) {
    // Swamp replaces each present, non-null value at the dot path.
    const keys = path.split(".");
    let parent: unknown = persisted;
    for (const key of keys.slice(0, -1)) {
      parent = parent !== null && typeof parent === "object"
        ? (parent as Record<string, unknown>)[key]
        : undefined;
    }
    const leaf = keys[keys.length - 1];
    if (parent === null || typeof parent !== "object") continue;
    const holder = parent as Record<string, unknown>;
    if (holder[leaf] !== undefined && holder[leaf] !== null) {
      holder[leaf] = "\${{ vault.get('vault', 'key') }}";
    }
  }
  const json = JSON.stringify(persisted);
  for (const field of fields) {
    assertEquals(json.includes(\`fixture-\${field}\`), false);
  }
}

/** Every secret argument of a method is marked sensitive. */
function assertSecretArgs(methodName: string, paths: string[]): void {
  const methods = model.methods as Record<string, { arguments: unknown }>;
  const marked = vaultedPaths(methods[methodName].arguments);
  for (const path of paths) {
    assertEquals(
      marked.includes(path),
      true,
      \`argument \${path} of \${methodName} is not marked sensitive\`,
    );
  }
}`;
}

/** One query argument a generated test sends, and what the server must see. */
interface QueryExpectation {
  /** Method argument name (identifier-safe). */
  field: string;
  /** API parameter name as it must appear on the wire. */
  name: string;
  /** Value passed to execute(). */
  value: string | string[];
  /** Values the server must receive under `name`, in order. */
  wire: string[];
}

/** Deterministic test value for a query parameter, plus its wire form. */
function queryExpectations(method: ClassifiedMethod): QueryExpectation[] {
  const out: QueryExpectation[] = [];
  // A query parameter sharing an argument name with a path parameter reuses
  // the path value, so it is not a separate query expectation.
  const seen = new Set<string>(
    method.operation.pathParams.map((p) => fieldName(p.name)),
  );
  for (const p of method.operation.queryParams) {
    const field = fieldName(p.name);
    if (seen.has(field)) continue;
    seen.add(field);
    if (p.schema?.type === "array") {
      // Values with a space and "&" prove query encoding survives the wire.
      const value = ["al pha", "be&ta"];
      out.push({
        field,
        name: p.name,
        value,
        wire: p.explode === false ? ["al pha,be&ta"] : value,
      });
      continue;
    }
    let value = "a b&c=d";
    if (p.schema?.enum && p.schema.enum.length > 0) {
      value = String(p.schema.enum[0]);
    } else if (p.schema?.type === "integer" || p.schema?.type === "number") {
      value = "7";
    } else if (p.schema?.type === "boolean") {
      value = "true";
    }
    out.push({ field, name: p.name, value, wire: [value] });
  }
  return out;
}

/** Argument value as execute() receives it (numbers/booleans stay typed). */
function queryArgValue(
  method: ClassifiedMethod,
  q: QueryExpectation,
): unknown {
  if (Array.isArray(q.value)) return q.value;
  const p = method.operation.queryParams.find((x) => x.name === q.name);
  if (p?.schema?.type === "integer" || p?.schema?.type === "number") {
    return Number(q.value);
  }
  if (p?.schema?.type === "boolean") return q.value === "true";
  return q.value;
}

/** Generate an execution test for a method */
function generateExecutionTest(
  config: ServiceConfig,
  method: ClassifiedMethod,
): string {
  const globalArgs = snykGlobalArgs(config);
  const fixture = generateJsonApiFixture(method);
  const routePath = extractFullPath(method.operation.path, config.scope);
  const httpMethod = method.operation.httpMethod.toUpperCase();
  const resourceName = testResourceName(method);
  const hasPathParam = method.operation.pathParams.length > 0;
  const queries = queryExpectations(method);

  const args: Record<string, unknown> = { ...buildTestArgs(method) };
  for (const q of queries) args[q.field] = queryArgValue(method, q);
  const writesBody = method.type === "create" || method.type === "update" ||
    (method.type === "action" && method.operation.requestBody !== undefined);
  // The body is every argument that is neither a path nor a query field, so
  // derive it from the spec's request properties, mirroring the model's args.
  const bodyFields: Record<string, unknown> = {};
  if (writesBody) {
    const taken = new Set([
      ...method.operation.pathParams.map((p) => fieldName(p.name)),
      ...queries.map((q) => q.field),
    ]);
    for (
      const [name, prop] of Object.entries(
        method.operation.requestBody?.properties ?? {},
      )
    ) {
      const field = fieldName(name);
      if (name === "id" || taken.has(field) || field in bodyFields) continue;
      bodyFields[field] = synthesizeField(name, prop);
    }
    Object.assign(args, bodyFields);
  }

  // Request-shape assertions shared by every method: exactly one request (the
  // mock returns a single page with links.next=null), the right verb and exact
  // path, the Snyk `version` query parameter, every declared query parameter
  // under its API name, and token auth. Write methods also check the JSON:API
  // content type and that the argument body was sent.
  const queryAsserts = queries.map((q) =>
    `      assertEquals(query.getAll(${JSON.stringify(q.name)}), ${
      JSON.stringify(q.wire)
    });`
  ).join("\n");
  const reqAsserts = `      assertEquals(requests.length, 1);
      const req0 = requests[0];
      assertEquals(req0.method, "${httpMethod}");
      assertEquals(req0.path, ${JSON.stringify(routePath)});
      const query = new URLSearchParams(req0.search);
      assertEquals(query.get("version"), "2024-10-15");${
    method.type === "list"
      ? `\n      assertEquals(query.get("limit"), "100");`
      : ""
  }${queryAsserts ? `\n${queryAsserts}` : ""}
      assertEquals(req0.headers["authorization"], "token test-token");${
    writesBody
      ? `\n      assertEquals(req0.headers["content-type"], "application/vnd.api+json");
      assertEquals(req0.body, ${JSON.stringify(bodyFields)});`
      : `\n      assertEquals(req0.body, null);`
  }`;

  const routeKey = `${httpMethod} ${routePath}`;
  const argsStr = Object.keys(args).length > 0 ? JSON.stringify(args) : "{}";
  const header = (verb: string, route: string) =>
    `Deno.test({
  name: "${config.name} model: ${method.name} ${verb}",
  sanitizeResources: false,
  fn: async () => {
${route}
    const uninstall = installFetchMock(url);

    try {
      const { context, getWrittenResources } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        definition: { id: "test-id", name: "test-${config.name}", version: 1, tags: {} },
      });
`;
  const footer = `    } finally {
      uninstall();
      await server.shutdown();
    }
  },
});`;

  if (method.type === "list") {
    return `${
      header(
        "fetches and writes resource",
        `    const mockItem = ${JSON.stringify(fixture)};
    const { url, server, requests } = startMockSnykServer({
      ${JSON.stringify(routeKey)}: { data: [mockItem], isCollection: true },
    });`,
      )
    }
      const result = await ${execCall(method.name, argsStr)};
      assertEquals(result.dataHandles.length, 1);

${reqAsserts}

      const resources = getWrittenResources();
      assertEquals(resources.length, 1);
      assertEquals(resources[0].specName, "${resourceName}");
      assertValidResource("${resourceName}", resources[0].data);
      const data = resources[0].data as { items: unknown[]; truncated: boolean };
      assertEquals(Array.isArray(data.items), true);
      assertEquals(data.items.length, 1);
      assertEquals(data.truncated, false);${listSecretAsserts(method)}${
      argSecretAsserts(method)
    }
${footer}`;
  }

  if (method.type === "delete") {
    // A successful DELETE answers 204 with no body; the helper must accept it.
    return `${
      header(
        "executes successfully",
        `    const { url, server, requests } = startMockSnykServer({
      ${JSON.stringify(routeKey)}: { status: 204 },
    });`,
      )
    }
      const result = await ${execCall(method.name, argsStr)};
      assertEquals(result.dataHandles.length, 0);

${reqAsserts}

      assertEquals(getWrittenResources().length, 0);${argSecretAsserts(method)}
${footer}`;
  }

  const verb = method.type === "get"
    ? "fetches and writes resource"
    : method.type === "create"
    ? "creates and writes resource"
    : "executes and writes resource";
  const mockData = method.type === "create"
    ? { ...fixture, id: "new-123" }
    : fixture;
  // A get/create the spec says answers without content (204, redirect) is
  // mocked that way: the method must succeed and store an empty resource.
  const noBody = (method.type === "get" || method.type === "create") &&
    !method.operation.hasResponseBody;
  const expectedInstance = method.type === "create"
    ? (noBody ? "created" : "new-123")
    : method.type === "get"
    ? (hasPathParam ? "test-id-123" : `${resourceName}-current`)
    : method.type === "update"
    ? (hasPathParam ? "test-id-123" : "updated")
    : `${resourceName}-current`;
  const dataAssert = noBody
    ? ""
    : method.type === "get"
    ? `\n      const data = resources[0].data as Record<string, unknown>;
      assertEquals(data.id, "fixture-123");`
    : method.type === "action"
    ? `\n      assertExists(resources[0].data);`
    : "";

  return `${
    header(
      verb,
      `${
        noBody ? "" : `    const mockData = ${JSON.stringify(mockData)};\n`
      }    const { url, server, requests } = startMockSnykServer({
      ${JSON.stringify(routeKey)}: ${
        noBody ? "{ status: 204 }" : "{ data: mockData }"
      },
    });`,
    )
  }
      const result = await ${execCall(method.name, argsStr)};
      assertEquals(result.dataHandles.length, 1);

${reqAsserts}

      const resources = getWrittenResources();
      assertEquals(resources.length, 1);
      assertEquals(resources[0].specName, "${resourceName}");
      assertValidResource("${resourceName}", resources[0].data);
      assertEquals(resources[0].name, "${expectedInstance}");${dataAssert}${
    noBody ? "" : flatSecretAsserts(method, resourceName)
  }${argSecretAsserts(method)}
${footer}`;
}

/** A flat writer's secrets must reach the written data and be vaulted. */
function flatSecretAsserts(
  method: ClassifiedMethod,
  resourceName: string,
): string {
  const fields = secretResponseFields(method);
  if (fields.length === 0) return "";
  return `\n      assertSecretsVaulted("${resourceName}", resources[0].data, ${
    JSON.stringify(fields)
  });`;
}

/** A list must drop item secrets: swamp cannot vault inside an array. */
function listSecretAsserts(method: ClassifiedMethod): string {
  const fields = secretListItemFields(method);
  if (fields.length === 0) return "";
  return `\n      const item = data.items[0] as Record<string, unknown>;
      for (const field of ${JSON.stringify(fields)}) {
        assertEquals((mockItem.attributes as Record<string, unknown>)[field], \`fixture-\${field}\`);
        assertEquals(field in item, false, \`\${field} was written in plaintext\`);
      }`;
}

/** Secret arguments must be marked sensitive. */
function argSecretAsserts(method: ClassifiedMethod): string {
  const paths = secretArgumentPaths(method);
  if (paths.length === 0) return "";
  return `\n      assertSecretArgs("${method.name}", ${
    JSON.stringify(paths)
  });`;
}

/** Standard test globalArgs for a service, including its scope id. */
function snykGlobalArgs(config: ServiceConfig): Record<string, string> {
  const scopeId = config.scope === "org"
    ? "orgId"
    : config.scope === "group"
    ? "groupId"
    : undefined;
  const g: Record<string, string> = {
    apiToken: "test-token",
    version: "2024-10-15",
  };
  if (scopeId) g[scopeId] = "test-org-123";
  return g;
}

/** The typed cast + execute call shared by every generated test. */
function execCall(methodName: string, argsStr: string): string {
  return `(model.methods as Record<string, { execute: (args: Record<string, unknown>, ctx: unknown) => Promise<{ dataHandles: unknown[] }> }>).${methodName}.execute(${argsStr}, context)`;
}

/** Resource key (specName) a method writes — mirrors the model generator. */
function testResourceName(method: ClassifiedMethod): string {
  return resourceNameOf(method);
}

/** Args passed to execute() in the error-path test. */
function buildExecuteArgs(method: ClassifiedMethod): Record<string, unknown> {
  return buildTestArgs(method);
}

/**
 * Generate one error-path test per service: a 5xx response must surface as a
 * thrown error, not a silent success or empty write.
 */
function generateErrorTest(
  config: ServiceConfig,
  method: ClassifiedMethod,
): string {
  const globalArgs = snykGlobalArgs(config);
  const args = buildExecuteArgs(method);
  const argsStr = Object.keys(args).length > 0 ? JSON.stringify(args) : "{}";
  return `Deno.test({
  name: "${config.name} model: ${method.name} surfaces API errors",
  sanitizeResources: false,
  fn: async () => {
    // A server that returns 500 for every request, exercising the error path.
    const originalFetch = globalThis.fetch;
    const server = Deno.serve({ port: 0, onListen() {} }, () =>
      new Response(
        JSON.stringify({
          jsonapi: { version: "1.0" },
          errors: [{ status: "500", detail: "Internal Server Error" }],
        }),
        {
          status: 500,
          headers: { "content-type": "application/vnd.api+json" },
        },
      ));
    const addr = server.addr as Deno.NetAddr;
    const mockUrl = \`http://localhost:\${addr.port}\`;
    globalThis.fetch = (input, init) => {
      const reqUrl = typeof input === "string" ? input : input.toString();
      return originalFetch(
        reqUrl.replace("https://api.snyk.io/rest", mockUrl),
        init,
      );
    };

    try {
      const { context } = createModelTestContext({
        globalArgs: ${JSON.stringify(globalArgs)},
        definition: { id: "test-id", name: "test-${config.name}", version: 1, tags: {} },
      });

      let threw = false;
      try {
        await ${execCall(method.name, argsStr)};
      } catch (_err) {
        threw = true;
      }
      assertEquals(threw, true);
    } finally {
      globalThis.fetch = originalFetch;
      await server.shutdown();
    }
  },
});`;
}

/** Generate a JSON:API fixture from a response schema */
function generateJsonApiFixture(
  method: ClassifiedMethod,
): Record<string, unknown> {
  const schema = method.operation.responseSchema;
  const base: Record<string, unknown> = {
    id: "fixture-123",
    type: "resource",
  };
  if (!schema?.properties) return base;

  const attributes: Record<string, unknown> = {};
  for (const [name, prop] of Object.entries(schema.properties)) {
    if (name === "id" || name === "type") continue;
    attributes[name] = synthesizeField(name, prop);
  }

  return { ...base, attributes };
}

/**
 * Synthesize a named property's value. A secret gets a recognizable
 * placeholder (`fixture-<name>`) rather than the spec's example, which can be
 * a real-looking token, and which the secret assertions look for.
 */
function synthesizeField(
  name: string,
  schema: SchemaObject,
  depth = 0,
): unknown {
  if (isSensitiveFieldName(name) && schema.type === "string") {
    return `fixture-${name}`;
  }
  return synthesizeValue(schema, depth);
}

/** Synthesize a value matching a schema (for test fixtures) */
function synthesizeValue(schema: SchemaObject, depth = 0): unknown {
  if (depth > 3) return null;

  if (schema.example !== undefined) return schema.example;
  if (schema.enum) return schema.enum[0];

  switch (schema.type) {
    case "string":
      if (schema.format === "date-time") return "2024-01-01T00:00:00Z";
      if (schema.format === "uri" || schema.format === "url") {
        return "https://example.com";
      }
      return "test-value";
    case "number":
    case "integer":
      return schema.minimum ?? 1;
    case "boolean":
      return true;
    case "array":
      return [];
    case "object":
      if (schema.properties) {
        const obj: Record<string, unknown> = {};
        for (const [name, prop] of Object.entries(schema.properties)) {
          obj[name] = synthesizeField(name, prop, depth + 1);
        }
        return obj;
      }
      return {};
    default:
      return null;
  }
}

/**
 * The exact request path a generated method sends, with the service's scope id
 * and every other path parameter replaced by the test values. The mock server
 * has no "/rest" prefix because the fetch mock strips the API base.
 */
function extractFullPath(path: string, scope: string): string {
  const scopeParam = scope === "org"
    ? "org_id"
    : scope === "group"
    ? "group_id"
    : null;
  return path.replace(
    /\{([^}]+)\}/g,
    (_, name) => name === scopeParam ? "test-org-123" : "test-id-123",
  );
}

/** Build test args that include path param values */
function buildTestArgs(method: ClassifiedMethod): Record<string, unknown> {
  const args: Record<string, unknown> = {};
  for (const p of method.operation.pathParams) {
    args[fieldName(p.name)] = "test-id-123";
  }
  return args;
}

/** Mirror of the model generator's argument-name sanitizer. */
function fieldName(name: string): string {
  return name
    .replace(/[^a-zA-Z0-9_]/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_|_$/g, "")
    .replace(/^\d/, "_$&");
}
